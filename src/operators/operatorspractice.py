# ARITHMETIC OPERATORS


# addition: add two values
add = 41 + 32
print(add)

# subtraction: subtract two values
sub = 41 - 32
print(sub)

# multiplication: multiply two values
mult = 41 * 32
print(mult)

# division: divide two values
div = 41 / 32
print(div)

# exponentiation: raise a value to the power of another value
exp = 41 ** 32
print(exp)

# low division: divide two values and round down to the nearest whole number
low_div = 41 // 32
print(low_div)

# modulus: get the remainder of a division operation
mod = 41 % 32
print(mod)










